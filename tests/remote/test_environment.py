def carrying(job_archive, text, node=("stepone", "0")):
    return job_archive(extra={environment.path_for(*node): text.encode()})


def submitted(server_client, key, token, archive):
    from test_server_jobs import stage, submit

    path, digest, size = archive
    job = stage(server_client, key, token, path, size)
    return outcome(server_client, key, token,
                   submit(server_client, key, token, job["id"], digest, size))


def slug(response):
    return (response.get_json().get("type") or "").rsplit("/", 1)[-1]


