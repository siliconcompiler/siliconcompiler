@pytest.fixture
def host_pip(monkeypatch):
    '''pip, and nothing else, stood in for: what it was asked to install, and
    an environment that holds it.'''
    from siliconcompiler.remote.server import pipbuild

    asked = []

    def install(requirements, site, constrain=(), proxy_socket=None, echo=None,
                indexes=(), allow_source=False):
        asked.append((open(requirements).read(), list(indexes), allow_source))
        import os
        os.makedirs(os.path.join(site, "numpy"))
        open(os.path.join(site, "numpy", "__init__.py"), "w").write("")
        return {"returncode": 0, "python": "cpython-test", "version": "3",
                "platform": "test", "installed": [["numpy", "2.0.1"]]}

    monkeypatch.setattr(pipbuild, "install", install)
    return asked


def test_an_upload_carrying_python_runs_to_the_end(server, server_client, key, token,
                                                   job_archive, host_pip):
    '''🔴 One upload through every step for real but pip: extracted; its file
    held to the format and installed while staging, wheels only, from the
    deployment's indexes, into the user's own cache; linked where the node's
    task looks; the user's code left where the run's tree has it; dispatched
    here; and run to the end.'''
    import time

    from conftest import call

    server.config["SC_CONFIG"]._values["features"] = \
        server.config["SC_CONFIG"]["features"] + ["python.env"]
    archive = job_archive(extra={
        environment.path_for("stepone", "0"): b"# generated\nnumpy==2.0.1\n",
        f"{environment.packages_path()}/helpers.py": b"VALUE = 1\n"})

    response = submitted(server_client, key, token, archive)
    assert response.status_code == 202, response.get_json()
    job_id = response.get_json()["id"]

    deadline = time.monotonic() + 120
    while True:
        job = call(server_client, key, "GET", f"/v1/jobs/{job_id}", token).get_json()
        if job["terminal"] or time.monotonic() > deadline:
            break
        time.sleep(0.5)
    assert job["state"] == "completed", job

    (text, indexes, from_source), = host_pip
    assert "numpy==2.0.1" in text.splitlines() and not from_source
    assert indexes == ["https://pypi.org/simple/"]

    jobs = server.config["SC_JOBS"]
    tree = jobs.job_root(job["owner"]["id"], job_id) / "gcd" / "job0"
    site = tree / environment.site_path("stepone", "0")
    assert site.is_symlink()
    assert str(site.resolve()).startswith(str(jobs.cache_dir(job["owner"]["id"]).resolve()))
    assert (site / "numpy" / "__init__.py").is_file()
    assert (tree / environment.packages_path() / "helpers.py").read_text() == "VALUE = 1\n"


@pytest.mark.parametrize("output,expected", [
    ("ERROR: No matching distribution found for numpy==2.0.1", "uninstallable"),
    ("WARNING: Retrying (Retry(total=4)) after connection broken by "
     "'NewConnectionError'\nERROR: No matching distribution found for numpy==2.0.1",
     "staging-failed"),
])
def test_a_line_that_will_not_install_rejects_the_job_before_any_node_runs(
        server, server_client, key, token, job_archive, dispatcher, monkeypatch,
        output, expected):
    '''🔴 Host mode installs while staging, so a line that will not install is
    `rejected`, `software-unavailable`, `uninstallable`, naming the package and
    the target -- not a failed run. An index that does not answer is this
    server's failure: `failed`, `staging-failed`.'''
    from conftest import call
    from siliconcompiler.remote.server import pipbuild

    def install(requirements, site, constrain=(), proxy_socket=None, echo=None,
                indexes=(), allow_source=False):
        return {"returncode": 1, "python": "cpython-test", "version": "3",
                "platform": "test-platform", "unresolved": pipbuild.named(output),
                "network": bool(pipbuild._NETWORK.search(output)), "tail": output}

    monkeypatch.setattr(pipbuild, "install", install)
    server.config["SC_CONFIG"]._values["features"] = \
        server.config["SC_CONFIG"]["features"] + ["python.env"]

    from test_server_jobs import stage, submit

    path, digest, size = carrying(job_archive, "numpy==2.0.1\n")
    created = stage(server_client, key, token, path, size)
    submit(server_client, key, token, created["id"], digest, size)
    job = call(server_client, key, "GET", f"/v1/jobs/{created['id']}", token).get_json()

    error = job["error"]
    if expected == "uninstallable":
        assert job["state"] == "rejected"
        assert (error["type"].rsplit("/", 1)[-1], error["reason"]) == \
            ("software-unavailable", "uninstallable")
        assert error["unresolved"][0]["name"] == "numpy"
        assert "cpython-test" in error["detail"] and "test-platform" in error["detail"]
    else:
        assert job["state"] == "failed"
        assert error["type"].endswith("/staging-failed")
    assert not dispatcher.submitted


@pytest.mark.parametrize("containers,available", [(False, []), (True, [])])
def test_a_python_name_nothing_here_holds_is_refused_at_create(
        server, server_client, key, token, containers, available):
    '''🔴 A server never ignores a listed name: host mode answers from its
    own Python, and where nodes run in containers, from the live images.'''
    from conftest import call

    server.config["SC_CONFIG"]._values["containers"] = containers
    response = call(server_client, key, "POST", "/v1/jobs", token, json={
        "design": "gcd", "jobname": "job0",
        "descriptor": {"requires": {"python": {"scnosuchdistribution": ["==1.0"]}}}})

    assert response.status_code == 422, response.get_json()
    body = response.get_json()
    assert slug(response) == "software-unavailable"
    assert body["unresolved"] == [{"name": "scnosuchdistribution",
                                   "requirement": ["==1.0"], "available": available}]


def test_host_mode_answers_from_its_own_python(server, server_client, key, token):
    from importlib.metadata import version

    from conftest import call

    ok = call(server_client, key, "POST", "/v1/jobs", token, json={
        "design": "gcd", "jobname": "job0",
        "descriptor": {"requires": {"python": {"packaging": [f"=={version('packaging')}"]}}}})
    assert ok.status_code == 201, ok.get_json()

    other = call(server_client, key, "POST", "/v1/jobs", token, json={
        "design": "gcd", "jobname": "job1",
        "descriptor": {"requires": {"python": {"packaging": ["==0.0.1"]}}}})
    assert other.status_code == 422
    assert other.get_json()["unresolved"][0]["available"] == [version("packaging")]


