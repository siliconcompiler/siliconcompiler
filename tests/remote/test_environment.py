def test_what_the_format_takes():
    parsed = parse(
        "# generated by SiliconCompiler",
        "",
        "numpy==2.0.1",
        "cocotb-bus[extra,other]==0.2.1 ; python_version >= '3.10'",
        "pyuvm==3.0.0   # a comment after whitespace",
    )

    assert [str(pin) for pin in parsed.pins] == [
        "numpy==2.0.1",
        "cocotb-bus[extra,other]==0.2.1 ; python_version >= '3.10'",
        "pyuvm==3.0.0"]


def test_the_file_is_where_the_contract_puts_it():
    assert environment.path_for("sim", "0") == "sc_python/nodes/sim/0/requirements.txt"
    assert environment.packages_path() == "sc_python/packages"


@pytest.mark.parametrize("line", [
    "numpy>=2.0",                              # a range
    "numpy==2.*",                              # a prefix
    "numpy===2.0",                             # arbitrary equality
    "numpy==2.0,<3",                           # two clauses
    "numpy",                                   # no version at all
    "numpy @ https://example.com/numpy.whl",   # a URL requirement
    "git+https://github.com/x/y.git",          # a VCS one
    "./local/package",                         # a local path
    "-e .",                                    # an editable
    "-i https://pypi.org/simple/",             # the short spelling
    "--index-url=https://pypi.org/simple/",    # the `=` spelling
    "--find-links https://example.com/",
    "--trusted-host example.com",
    "-r other.txt", "-c constraints.txt",
    "numpy==2.0 --hash=sha256:abc",
    "numpy==2.0 \\",                           # a continuation
    "numpy==2.0#no-space-before-it",
    "numpy==2.0 ; not a marker (",
    # 🔴 No line names an index: every package comes from the deployment's own.
    "--index-url https://pypi.org/simple/",
    "--extra-index-url https://files.pythonhosted.org/",
    "--index-url https://user:token@example.com/simple/",
])
def test_everything_else_is_refused(line):
    with pytest.raises(EnvironmentFileError):
        parse(line)


def test_a_file_may_list_nothing():
    '''Legal, though the client writes none for a node with no line.'''
    parsed = parse("# Generated by SiliconCompiler", "", "   # and nothing else")

    assert parsed.pins == []


def test_each_name_once_as_pep_503_sees_it():
    with pytest.raises(EnvironmentFileError, match="twice"):
        parse("Cocotb_Bus==0.2.1", "cocotb-bus==0.2.1")


def test_the_bounds():
    with pytest.raises(EnvironmentFileError, match="lines"):
        parse(*[f"p{n}==1.0" for n in range(environment.MAX_LINES + 1)])
    with pytest.raises(EnvironmentFileError, match="bytes"):
        environment.parse(b"#" * (environment.MAX_BYTES + 1))
    with pytest.raises(EnvironmentFileError, match="UTF-8"):
        environment.parse(b"\xff\xfe==1.0\n")


def test_what_is_rendered_is_what_is_parsed():
    '''A builder writes its own file from what parsed; it reads back the same.'''
    parsed = parse("numpy==2.0.1", "pyuvm==3.0.0 ; sys_platform == 'linux'")

    again = environment.parse(environment.render(
        parsed.pins, header="written by the builder").encode())

    assert again == parsed


